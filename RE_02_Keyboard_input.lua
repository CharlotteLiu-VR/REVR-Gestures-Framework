local ScanCode = {}
local ScanToVK = {}
for name, vk_code in pairs(VK) do
    local scan_code = VKToScan[vk_code]
    if scan_code ~= nil then
        ScanCode[name] = scan_code
    end
end
for vk_code, scan_code in pairs(VKToScan) do
    ScanToVK[scan_code] = vk_code
end

local function resolve_key(value)
    if value == nil then
        return nil
    end

    if type(value) == "number" then
        return VKToScan[value] or value
    end

    if type(value) == "string" then
        local vk_code = VK[value]
        if vk_code ~= nil then
            return VKToScan[vk_code] or vk_code
        end
    end

    return nil
end

local function resolve_virtual_key(value)
    if value == nil then
        return nil
    end

    if type(value) == "number" then
        if VKToName[value] ~= nil then
            return value
        end
        return ScanToVK[value]
    end

    if type(value) == "string" then
        return VK[value]
    end

    return nil
end

local function describe_virtual_key(value)
    local vk_code = resolve_virtual_key(value)
    if vk_code == nil then
        return "unknown"
    end

    return VKToName[vk_code] or ("VK_" .. tostring(vk_code))
end

