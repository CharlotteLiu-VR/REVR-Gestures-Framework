local function describe_mouse_button(button)
    if button == MouseButton.Left then
        return "mouse left"
    end
    if button == MouseButton.Right then
        return "mouse right"
    end
    if button == MouseButton.Middle then
        return "mouse middle"
    end
    if button == MouseButton.X1 then
        return "mouse x1"
    end
    if button == MouseButton.X2 then
        return "mouse x2"
    end
    if button == MouseButton.WheelDown then
        return "mouse wheel down"
    end
    if button == MouseButton.WheelUp then
        return "mouse wheel up"
    end
    return "mouse " .. tostring(button)
end

